def notice(purpose: str, language: str) -> str:
    try:
        return NOTICES[purpose][language]
    except KeyError as exc:
        raise ValueError("This purpose/language notice is not available offline") from exc


class ConsentDecision(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)
    purpose: str
    decision: Literal["granted", "refused", "undecided", "withdrawn"]
    language: str
    party: str
    method: Literal["touch", "voice"]
    version: str = NOTICE_VERSION
    notice_text: str
    notice_hash: str
    recorded_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class ConsentLedger(BaseModel):
    model_config = ConfigDict(extra="forbid")
    decisions: list[ConsentDecision] = Field(default_factory=list)

    def record(
        self, purpose: str, decision: str, language: str, party: str, method: str = "touch"
    ) -> None:
        if purpose not in PURPOSES:
            raise ValueError("Unknown permission purpose")
        text = notice(purpose, language)
        self.decisions.append(
            ConsentDecision(
                purpose=purpose,
                decision=decision,
                language=language,
                party=party,
                method=method,
                notice_text=text,
                notice_hash=hashlib.sha256(text.encode()).hexdigest(),
            )
        )

    def allows(self, purpose: str) -> bool:
        latest = next((d for d in reversed(self.decisions) if d.purpose == purpose), None)
        return latest is not None and latest.decision == "granted"

    def withdraw(self, purpose: str) -> None:
        latest = next((d for d in reversed(self.decisions) if d.purpose == purpose), None)
        if latest is None:
            raise ValueError("No prior permission")
        self.record(purpose, "withdrawn", latest.language, latest.party, latest.method)
